local function event_opts(item)
  local opts = { phase = item.phase or "default" }
  opts.actor = "victim"
  if item.source == "sentinelone_endpoint" or item.source == "microsoft_windows_eventlog" then
    local payload = item.event
    local endpoint = payload["endpoint.name"] or payload.ComputerName or ""
    if endpoint == "HOST-01" then opts.host = "secondary_workstation" else opts.host = "primary_workstation" end
  end
  return opts
end

local function send_alert_plan(sender, story)
  for _, plan in ipairs(alerts) do
    local opts = {
      phase = plan.phase,
      host = plan.host,
      actor = plan.actor or "victim",
      offset_minutes = plan.offset_minutes or 0,
    }
    local result = sender:alert(plan.template, plan.overrides, opts)
    if not result.success then
      table.insert(story.warnings, string.format("alert send failed (%s)", plan.id or plan.template))
    end
  end
end

scenario.run = function(sender, story)
  story:correlate("source_scenario", "identity_theft_ransomware_scenario.py")
