  local current_phase = nil
  for _, item in ipairs(events) do
    if item.phase ~= current_phase then current_phase = item.phase; story:phase(current_phase) end
    sender:hec_event(item.source, item.event, event_opts(item))
  end
  send_alert_plan(sender, story)
  sender:ti(story:iocs(), { phase = "ransomware_execution" })
end

